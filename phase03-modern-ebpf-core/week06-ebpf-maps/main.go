//go:build linux
// +build linux

package main

//go:generate go run github.com/cilium/ebpf/cmd/bpf2go -cc clang bpf syscall_stats.c

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"os/signal"
	"sort"
	"syscall"
	"time"

	"github.com/cilium/ebpf/link"
	"github.com/cilium/ebpf/rlimit"
)

// ProcessRecord holds extracted syscall statistics for CLI presentation
type ProcessRecord struct {
	PID   uint32
	Comm  string
	Count uint64
}

func main() {
	fmt.Println("======================================================================")
	fmt.Println(" eBPF Syscall Top Monitor (BPF_MAP_TYPE_HASH + Cilium ebpf-go)")
	fmt.Println("======================================================================")

	// Remove locked memory limit for eBPF allocations
	if err := rlimit.RemoveMemlock(); err != nil {
		log.Fatalf("Failed to remove memlock limit: %v", err)
	}

	// Load BPF objects generated by bpf2go
	var objs bpfObjects
	if err := loadBpfObjects(&objs, nil); err != nil {
		log.Fatalf("Failed to load eBPF objects: %v", err)
	}
	defer objs.Close()

	// Attach program to raw_syscalls/sys_enter tracepoint
	tp, err := link.Tracepoint("raw_syscalls", "sys_enter", objs.TrackSyscalls, nil)
	if err != nil {
		log.Fatalf("Failed to attach tracepoint to raw_syscalls/sys_enter: %v", err)
	}
	defer tp.Close()

	log.Printf("Successfully attached to tracepoint 'raw_syscalls/sys_enter'!\n")
	log.Printf("Collecting syscall frequencies across all processes... (Press Ctrl+C to stop)\n\n")

	// Set up signal handler for graceful shutdown
	stopper := make(chan os.Signal, 1)
	signal.Notify(stopper, os.Interrupt, syscall.SIGTERM)

	// Refresh table every 2 seconds
	ticker := time.NewTicker(2 * time.Second)
	defer ticker.Stop()

	for {
		select {
		case <-ticker.C:
			renderTopSyscalls(&objs)

		case sig := <-stopper:
			fmt.Printf("\nReceived signal '%s'. Rendering final report...\n", sig)
			renderTopSyscalls(&objs)
			fmt.Println("Shutting down eBPF monitor cleanly.")
			return
		}
	}
}

// renderTopSyscalls iterates over the eBPF hash map, sorts the records, and renders a formatted table
func renderTopSyscalls(objs *bpfObjects) {
	var records []ProcessRecord
	var totalSyscalls uint64

	var pid uint32
	var stat bpfProcStat

	// Iterate through all key-value entries in the BPF hash map
	iter := objs.SyscallMap.Iterate()
	for iter.Next(&pid, &stat) {
		// Clean null-terminated comm string
		commStr := string(bytes.TrimRight(stat.Comm[:], "\x00"))
		if commStr == "" {
			commStr = "<unknown>"
		}

		records = append(records, ProcessRecord{
			PID:   pid,
			Comm:  commStr,
			Count: stat.Count,
		})
		totalSyscalls += stat.Count
	}

	if err := iter.Err(); err != nil {
		log.Printf("Error iterating over syscall_map: %v", err)
		return
	}

	// Sort processes descending by syscall invocation count
	sort.Slice(records, func(i, j int) bool {
		return records[i].Count > records[j].Count
	})

	// Render formatted CLI dashboard
	fmt.Printf("\033[H\033[2J") // Clear terminal screen
	fmt.Println("=================================================================================")
	fmt.Printf(" eBPF Syscall Monitor | Time: %s | Total Invocations: %d\n",
		time.Now().Format("15:04:05"), totalSyscalls)
	fmt.Println("=================================================================================")
	fmt.Printf("%-5s  %-8s  %-18s  %-16s  %-12s\n", "RANK", "PID", "COMM", "SYSCALLS", "SHARE (%)")
	fmt.Println("---------------------------------------------------------------------------------")

	maxDisplay := 10
	if len(records) < maxDisplay {
		maxDisplay = len(records)
	}

	for i := 0; i < maxDisplay; i++ {
		rec := records[i]
		var share float64
		if totalSyscalls > 0 {
			share = (float64(rec.Count) / float64(totalSyscalls)) * 100.0
		}
		fmt.Printf("#%-4d  %-8d  %-18s  %-16d  %6.2f%%\n",
			i+1, rec.PID, rec.Comm, rec.Count, share)
	}

	if len(records) == 0 {
		fmt.Println(" (Waiting for process syscall activity...)")
	}

	fmt.Println("---------------------------------------------------------------------------------")
	fmt.Printf(" Tracking %d active processes in BPF_MAP_TYPE_HASH\n\n", len(records))
}
